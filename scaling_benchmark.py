"""
scaling_benchmark.py
Measures how the FRAG detector scales with log size.

For each target size (events per log) and each repetition:
  1. Build a scaled log at CONSTANT WORKLOAD DENSITY (see below).
  2. Time FRAG (graph construction + three detection passes) and the
     time-window baseline.
  3. Measure FRAG's peak Python heap allocation (tracemalloc, separate run
     so it does not distort the timing).
  4. Score both detectors against ground truth with evaluate_v2 (the same
     race-instance matching used for the paper's tables).

Then fit runtime against size (linear fit + log-log slope) and write
a CSV of every run, a JSON summary with machine info, and a chart.

Constant-density scaling:
  A log of N events is built from K consecutive segments, each generated by
  log_generator.generate_log() exactly as for the paper's logs (200-800
  background events, 8-40 injected races, 50-patient pool, 10 s window).
  Segment k is shifted by k * SEGMENT_SPAN_MS in time and gets its own
  patient namespace, so events per resource, events per second, and race
  density all match the paper's logs. Segments are added until the log has
  at least N events. What grows is the log: more events, resources and
  races for the detector to process in one graph. What does NOT grow is
  contention on any single resource. That would be a different experiment.

Usage:
  python scaling_benchmark.py                          # default sizes, 3 reps
  python scaling_benchmark.py --sizes 1000 5000 25000 --reps 3
  python scaling_benchmark.py --outdir results/scaling
"""

import argparse
import csv
import gc
import json
import math
import os
import platform
import time
import tracemalloc
from pathlib import Path

import numpy as np

from log_generator import build_resource_pool, generate_log
from race_detector_v2 import detect_all
from baseline_scanner import scan
from evaluate_v2 import evaluate_log, aggregate_metrics

SEGMENT_SPAN_MS = 11000.0   # 10 s generator window + 1 s gap between segments
DEFAULT_SIZES   = [1000, 5000, 10000, 25000, 50000, 100000]
CLASSES         = ["SWC", "TAV", "CUR", "Overall"]


# ── SCALED LOG ────────────────────────────────────────────────────────────────

def build_scaled_log(target_events, condition, rng, n_patients=50):
    """Concatenate constant-density segments until the log has >= target_events."""
    pool = build_resource_pool(n_patients)
    events = []
    n_swc = n_tav = n_cur = 0
    k = 0
    while len(events) < target_events:
        seg = generate_log(f"seg{k}", condition, rng, pool)
        offset = k * SEGMENT_SPAN_MS
        for ev in seg["events"]:
            ev["timestamp_ms"] = round(ev["timestamp_ms"] + offset, 3)
            ev["resource_id"] = ev["resource_id"].replace("patient-", f"s{k:05d}-patient-")
        events.extend(seg["events"])      # segments are time-ordered, so log stays sorted
        n_swc += seg["n_swc"]; n_tav += seg["n_tav"]; n_cur += seg["n_cur"]
        k += 1

    for i, ev in enumerate(events):
        ev["event_id"] = i

    return {
        "log_id":     f"scaled_{target_events}",
        "condition":  condition,
        "n_events":   len(events),
        "n_races":    n_swc + n_tav + n_cur,
        "n_swc":      n_swc,
        "n_tav":      n_tav,
        "n_cur":      n_cur,
        "n_segments": k,
        "events":     events,
    }


# ── MEASUREMENT ───────────────────────────────────────────────────────────────

def timed(fn, arg):
    gc.collect()
    t0 = time.perf_counter()
    out = fn(arg)
    return out, time.perf_counter() - t0


def peak_alloc_mb(fn, arg):
    gc.collect()
    tracemalloc.start()
    fn(arg)
    _, peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    return peak / 2**20


def run_one(target, rep, condition, seed):
    rng = np.random.default_rng(seed + 1000 * rep + target)
    log = build_scaled_log(target, condition, rng)

    frag_res, t_frag = timed(detect_all, log)
    base_res, t_base = timed(scan, log)
    mem_mb = peak_alloc_mb(detect_all, log)

    fc, bc = evaluate_log(log, frag_res, base_res)
    frag_m, base_m = aggregate_metrics([fc], [bc])

    row = {
        "target_events": target,
        "rep":           rep,
        "n_events":      log["n_events"],
        "n_segments":    log["n_segments"],
        "n_races_gt":    log["n_races"],
        "frag_time_s":   t_frag,
        "base_time_s":   t_base,
        "frag_events_per_s": log["n_events"] / t_frag,
        "frag_peak_mb":  mem_mb,
    }
    for cls in CLASSES:
        row[f"frag_f1_{cls}"] = frag_m[cls][2]
        row[f"base_f1_{cls}"] = base_m[cls][2]
    row["frag_p_Overall"] = frag_m["Overall"][0]
    row["frag_r_Overall"] = frag_m["Overall"][1]
    return row


# ── ANALYSIS ──────────────────────────────────────────────────────────────────

def fit_runtime(rows):
    """Least-squares fits over every run: linear (t = a*n + b) and power law (t ∝ n^k)."""
    n = np.array([r["n_events"] for r in rows], dtype=float)
    t = np.array([r["frag_time_s"] for r in rows], dtype=float)

    a, b = np.polyfit(n, t, 1)
    pred = a * n + b
    ss_res = float(np.sum((t - pred) ** 2))
    ss_tot = float(np.sum((t - t.mean()) ** 2))
    r2 = 1 - ss_res / ss_tot if ss_tot > 0 else 1.0

    k, logc = np.polyfit(np.log(n), np.log(t), 1)
    return {
        "linear_slope_s_per_event": float(a),
        "linear_intercept_s":       float(b),
        "linear_r2":                r2,
        "loglog_exponent":          float(k),
        "loglog_coeff":             float(math.exp(logc)),
    }


def summarize(rows, sizes):
    out = []
    for size in sizes:
        rs = [r for r in rows if r["target_events"] == size]
        s = {"target_events": size, "reps": len(rs),
             "n_events_mean": float(np.mean([r["n_events"] for r in rs]))}
        for key in ["frag_time_s", "base_time_s", "frag_peak_mb", "frag_events_per_s"] + \
                   [f"frag_f1_{c}" for c in CLASSES] + [f"base_f1_{c}" for c in CLASSES]:
            vals = [r[key] for r in rs]
            s[f"{key}_mean"] = float(np.mean(vals))
            s[f"{key}_std"]  = float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0
        s["frag_time_s_median"] = float(np.median([r["frag_time_s"] for r in rs]))
        out.append(s)
    return out


def machine_info():
    info = {
        "platform":  platform.platform(),
        "python":    platform.python_version(),
        "processor": platform.processor() or platform.machine(),
        "cpu_count": os.cpu_count(),
    }
    try:
        with open("/proc/cpuinfo") as f:
            for line in f:
                if line.startswith("model name"):
                    info["cpu_model"] = line.split(":", 1)[1].strip()
                    break
        with open("/proc/meminfo") as f:
            kb = int(f.readline().split()[1])
            info["ram_gb"] = round(kb / 2**20, 1)
    except OSError:
        pass
    try:
        import networkx
        info["networkx"] = networkx.__version__
    except ImportError:
        pass
    info["numpy"] = np.__version__
    return info


# ── OUTPUT ────────────────────────────────────────────────────────────────────

def print_summary(summary, fit):
    print("\n" + "=" * 86)
    print("FRAG Scaling Benchmark  (mean ± std over reps; time = graph build + 3 passes)")
    print("=" * 86)
    print(f"{'Events':>9} {'FRAG time (s)':>16} {'Events/s':>10} {'Peak MB':>9} "
          f"{'F1 FRAG':>9} {'F1 Base':>9} {'Base time (s)':>14}")
    print("-" * 86)
    for s in summary:
        print(f"{s['n_events_mean']:>9,.0f} "
              f"{s['frag_time_s_mean']:>8.3f} ± {s['frag_time_s_std']:<5.3f} "
              f"{s['frag_events_per_s_mean']:>10,.0f} "
              f"{s['frag_peak_mb_mean']:>9.1f} "
              f"{s['frag_f1_Overall_mean']*100:>8.1f}% "
              f"{s['base_f1_Overall_mean']*100:>8.1f}% "
              f"{s['base_time_s_mean']:>14.3f}")
    print("-" * 86)
    print(f"Linear fit:  t = {fit['linear_slope_s_per_event']*1e6:.2f} µs/event · n "
          f"+ {fit['linear_intercept_s']:.3f} s   (R² = {fit['linear_r2']:.4f})")
    print(f"Log-log fit: t ∝ n^{fit['loglog_exponent']:.3f}   (1.0 = linear, 2.0 = quadratic)")
    print("=" * 86 + "\n")


def save_chart(rows, summary, fit, outdir):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not available — skipping chart")
        return

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4.5))

    n = [r["n_events"] for r in rows]
    ax1.scatter(n, [r["frag_time_s"] for r in rows], color="#1f4e79", s=18,
                label="FRAG runs", zorder=3)
    xs = np.linspace(0, max(n) * 1.05, 100)
    ax1.plot(xs, fit["linear_slope_s_per_event"] * xs + fit["linear_intercept_s"],
             color="#1f4e79", linestyle="--", linewidth=1,
             label=f"Linear fit (R² = {fit['linear_r2']:.3f})")
    ax1.set_xlabel("Events per log")
    ax1.set_ylabel("Runtime (s)")
    ax1.set_title(f"FRAG runtime vs. log size  (t ∝ n^{fit['loglog_exponent']:.2f})")
    ax1.grid(linestyle="--", alpha=0.4)
    ax1.legend(fontsize=9)

    sx = [s["n_events_mean"] for s in summary]
    ax2.errorbar(sx, [s["frag_f1_Overall_mean"] * 100 for s in summary],
                 yerr=[s["frag_f1_Overall_std"] * 100 for s in summary],
                 marker="o", color="#1f4e79", capsize=3, label="FRAG")
    ax2.errorbar(sx, [s["base_f1_Overall_mean"] * 100 for s in summary],
                 yerr=[s["base_f1_Overall_std"] * 100 for s in summary],
                 marker="s", color="#a9c4e0", capsize=3, label="Baseline")
    ax2.set_xscale("log")
    ax2.set_ylim(0, 100)
    ax2.set_xlabel("Events per log (log scale)")
    ax2.set_ylabel("Overall F1 (%)")
    ax2.set_title("Detection accuracy vs. log size")
    ax2.grid(linestyle="--", alpha=0.4)
    ax2.legend(fontsize=9)

    plt.tight_layout()
    path = os.path.join(outdir, "scaling_chart.png")
    plt.savefig(path, dpi=150)
    plt.close()
    print(f"Chart saved → {path}")


# ── MAIN ──────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="FRAG scaling benchmark")
    parser.add_argument("--sizes", type=int, nargs="+", default=DEFAULT_SIZES,
                        help="Target events per log (default: %(default)s)")
    parser.add_argument("--reps", type=int, default=3,
                        help="Repetitions per size (default 3)")
    parser.add_argument("--condition", default="C2", choices=["C2", "C3"],
                        help="Workload condition for every segment (default C2)")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--outdir", default="results/scaling")
    args = parser.parse_args()

    Path(args.outdir).mkdir(parents=True, exist_ok=True)
    sizes = sorted(args.sizes)

    # Warm-up so import / first-call costs don't land in the smallest size
    run_one(sizes[0], rep=-1, condition=args.condition, seed=args.seed)

    rows = []
    for size in sizes:
        for rep in range(args.reps):
            row = run_one(size, rep, args.condition, args.seed)
            rows.append(row)
            print(f"  size {size:>7,}  rep {rep+1}/{args.reps}:  "
                  f"{row['n_events']:>7,} events  {row['frag_time_s']:7.3f} s  "
                  f"{row['frag_peak_mb']:7.1f} MB  F1 {row['frag_f1_Overall']*100:5.1f}%")

    summary = summarize(rows, sizes)
    fit = fit_runtime(rows)
    print_summary(summary, fit)

    csv_path = os.path.join(args.outdir, "scaling_runs.csv")
    with open(csv_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print(f"Runs saved → {csv_path}")

    info = machine_info()
    try:
        import resource   # not available on Windows
        info["peak_rss_mb"] = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024
    except ImportError:
        pass
    out = {
        "config": {"sizes": sizes, "reps": args.reps, "condition": args.condition,
                   "seed": args.seed, "segment_span_ms": SEGMENT_SPAN_MS,
                   "scaling": "constant density (paper-sized segments, disjoint patient namespaces)"},
        "machine": info,
        "fit":     fit,
        "summary": summary,
    }
    json_path = os.path.join(args.outdir, "scaling_summary.json")
    with open(json_path, "w") as f:
        json.dump(out, f, indent=2)
    print(f"Summary saved → {json_path}")

    save_chart(rows, summary, fit, args.outdir)


if __name__ == "__main__":
    main()
